-- =============================================================================
-- ESQUEMA COMPLETO DE BASE DE DATOS (SISTEMA DE GESTIÓN Y PANADERÍA)
-- Basado en el estado actual de Supabase PostgreSQL
-- =============================================================================

-- 1. TABLA: rol
CREATE TABLE IF NOT EXISTS public.rol (
    id_rol BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(50) NOT NULL,
    descripcion VARCHAR(255),
    estado BOOLEAN NOT NULL DEFAULT true
);

-- 2. TABLA: usuario
CREATE TABLE IF NOT EXISTS public.usuario (
    id_usuario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_rol BIGINT NOT NULL REFERENCES public.rol(id_rol),
    nombre VARCHAR(100) NOT NULL,
    apellido VARCHAR(100),
    nombre_usuario VARCHAR(100) NOT NULL,
    contrasena_hash VARCHAR(255),
    estado BOOLEAN NOT NULL DEFAULT true,
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT now(),
    ultimo_acceso TIMESTAMPTZ
);

-- 3. TABLA: auditoria
CREATE TABLE IF NOT EXISTS public.auditoria (
    id_auditoria BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_usuario BIGINT REFERENCES public.usuario(id_usuario),
    accion VARCHAR(50) NOT NULL,
    tabla_afectada VARCHAR(100),
    registro_id BIGINT,
    fecha_hora TIMESTAMPTZ NOT NULL DEFAULT now(),
    detalle TEXT
);

-- ===== INICIO DE MI IMPLEMENTACIÓN - RF-01 =====
-- 4. TABLA: producto
-- Esta tabla guarda en la base de datos de Supabase todos los productos que se registran en el sistema.
-- Recibe los datos que envía el repositorio (server/repositories/producto.repository.ts).
-- Aquí la base de datos genera automáticamente el id_producto y la fecha_creacion.
CREATE TABLE IF NOT EXISTS public.producto (
    id_producto BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre VARCHAR(150) NOT NULL,
    descripcion TEXT,
    categoria VARCHAR(100),
    unidad_medida VARCHAR(30) NOT NULL,
    stock_actual NUMERIC NOT NULL DEFAULT 0,
    stock_minimo NUMERIC NOT NULL DEFAULT 0,
    estado BOOLEAN NOT NULL DEFAULT true,
    fecha_creacion TIMESTAMPTZ NOT NULL DEFAULT now()
);
-- ===== FIN DE MI IMPLEMENTACIÓN - RF-01 =====

-- 5. TABLA: lote
CREATE TABLE IF NOT EXISTS public.lote (
    id_lote BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_producto BIGINT NOT NULL REFERENCES public.producto(id_producto),
    numero_lote VARCHAR(50) NOT NULL,
    cantidad NUMERIC NOT NULL DEFAULT 0,
    fecha_produccion DATE,
    fecha_vencimiento DATE,
    estado BOOLEAN NOT NULL DEFAULT true
);

-- 6. TABLA: destinatario
CREATE TABLE IF NOT EXISTS public.destinatario (
    id_destinatario BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre_empresa VARCHAR(150) NOT NULL,
    telefono VARCHAR(30),
    correo VARCHAR(150),
    direccion VARCHAR(255),
    estado BOOLEAN NOT NULL DEFAULT true
);

-- 7. TABLA: pedido
CREATE TABLE IF NOT EXISTS public.pedido (
    id_pedido BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_destinatario BIGINT NOT NULL REFERENCES public.destinatario(id_destinatario),
    id_usuario BIGINT NOT NULL REFERENCES public.usuario(id_usuario),
    fecha_registro TIMESTAMPTZ NOT NULL DEFAULT now(),
    fecha_entrega DATE,
    estado VARCHAR(30) NOT NULL DEFAULT 'PENDIENTE',
    prioridad VARCHAR(20) NOT NULL DEFAULT 'NORMAL',
    encargado_entrega VARCHAR(150),
    observaciones TEXT
);

-- 8. TABLA: detalle_pedido
CREATE TABLE IF NOT EXISTS public.detalle_pedido (
    id_detalle_pedido BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido BIGINT NOT NULL REFERENCES public.pedido(id_pedido),
    id_producto BIGINT NOT NULL REFERENCES public.producto(id_producto),
    cantidad NUMERIC NOT NULL,
    cantidad_entregada NUMERIC NOT NULL DEFAULT 0
);

-- 9. TABLA: produccion
CREATE TABLE IF NOT EXISTS public.produccion (
    id_produccion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido BIGINT REFERENCES public.pedido(id_pedido),
    id_producto BIGINT NOT NULL REFERENCES public.producto(id_producto),
    id_usuario BIGINT NOT NULL REFERENCES public.usuario(id_usuario),
    id_lote BIGINT REFERENCES public.lote(id_lote),
    cantidad_planificada NUMERIC NOT NULL,
    cantidad_producida NUMERIC NOT NULL DEFAULT 0,
    estado VARCHAR(30) NOT NULL DEFAULT 'PENDIENTE',
    fecha_produccion DATE NOT NULL DEFAULT CURRENT_DATE,
    tiempo_real VARCHAR(50),
    observaciones TEXT
);

-- 10. TABLA: perdida
CREATE TABLE IF NOT EXISTS public.perdida (
    id_perdida BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_producto BIGINT NOT NULL REFERENCES public.producto(id_producto),
    id_lote BIGINT REFERENCES public.lote(id_lote),
    id_usuario BIGINT NOT NULL REFERENCES public.usuario(id_usuario),
    cantidad NUMERIC NOT NULL,
    motivo VARCHAR(150) NOT NULL,
    tipo_perdida VARCHAR(50),
    fecha DATE NOT NULL DEFAULT CURRENT_DATE,
    observaciones TEXT
);

-- 11. TABLA: devolucion
CREATE TABLE IF NOT EXISTS public.devolucion (
    id_devolucion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_pedido BIGINT NOT NULL REFERENCES public.pedido(id_pedido),
    id_producto BIGINT NOT NULL REFERENCES public.producto(id_producto),
    id_lote BIGINT REFERENCES public.lote(id_lote),
    id_usuario BIGINT NOT NULL REFERENCES public.usuario(id_usuario),
    cantidad_devuelta NUMERIC NOT NULL,
    motivo VARCHAR(150) NOT NULL,
    fecha DATE NOT NULL DEFAULT CURRENT_DATE,
    estado VARCHAR(30) NOT NULL DEFAULT 'PENDIENTE',
    observaciones TEXT
);

-- 12. TABLA: movimiento_inventario
CREATE TABLE IF NOT EXISTS public.movimiento_inventario (
    id_movimiento BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    id_producto BIGINT NOT NULL REFERENCES public.producto(id_producto),
    id_lote BIGINT REFERENCES public.lote(id_lote),
    id_produccion BIGINT REFERENCES public.produccion(id_produccion),
    id_perdida BIGINT REFERENCES public.perdida(id_perdida),
    id_devolucion BIGINT REFERENCES public.devolucion(id_devolucion),
    id_usuario BIGINT NOT NULL REFERENCES public.usuario(id_usuario),
    tipo_movimiento VARCHAR(40) NOT NULL,
    cantidad NUMERIC NOT NULL,
    stock_anterior NUMERIC NOT NULL,
    stock_nuevo NUMERIC NOT NULL,
    fecha TIMESTAMPTZ NOT NULL DEFAULT now(),
    observaciones TEXT
);

-- 13. TABLA: configuracion
CREATE TABLE IF NOT EXISTS public.configuracion (
    id_configuracion BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    dias_alerta_vencimiento INTEGER NOT NULL DEFAULT 3,
    estado BOOLEAN NOT NULL DEFAULT true,
    fecha_actualizacion TIMESTAMPTZ NOT NULL DEFAULT now()
);
